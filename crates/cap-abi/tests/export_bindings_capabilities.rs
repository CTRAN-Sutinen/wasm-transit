//! The engine's typed op map (`web/src/types/caps.ts`), written with the
//! ts-rs bindings (`just types`): each capability's request and answer,
//! by its id. The capabilities are the `crates/cap-*` directories, so a
//! new capability is in the map with no line here or in the engine.

use std::fs;
use std::path::{Path, PathBuf};

fn pascal(id: &str) -> String {
    id.split(['-', '_'])
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

#[test]
fn export_bindings_capability_map() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut ids: Vec<String> = fs::read_dir(root.join("crates"))
        .expect("crates/")
        .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
        .filter_map(|name| name.strip_prefix("cap-").map(str::to_string))
        .filter(|id| id != "abi")
        .collect();
    ids.sort();
    let mut text = String::from(
        "// GENERATED by cap-abi's export_bindings_capability_map test (`just types`):\n\
         // each capability's request and answer, by its id.\n\n",
    );
    for id in &ids {
        let (name, dir) = (pascal(id), format!("cap_{}", id.replace('-', "_")));
        text += &format!("import type {{ Request as {name}Request }} from \"./{dir}/Request\";\n");
        text +=
            &format!("import type {{ Response as {name}Response }} from \"./{dir}/Response\";\n");
    }
    text += "\nexport type Caps = {\n";
    for id in &ids {
        let name = pascal(id);
        text += &format!(
            "  {}: [{name}Request, {name}Response];\n",
            id.replace('-', "_")
        );
    }
    text += "};\n";
    let dir = std::env::var("TS_RS_EXPORT_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| root.join("web/src/types"));
    let dir = if dir.is_absolute() {
        dir
    } else {
        root.join(dir)
    };
    fs::create_dir_all(&dir).expect("the bindings' directory");
    fs::write(dir.join("caps.ts"), text).expect("write caps.ts");
}
