#![allow(dead_code)] // each bin uses part of the listing
//! The assemblies the tree asks for, and the files that are each one
//! (shared by gen-assemblies, which writes them, and gen-manifest,
//! which records them).

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

/// One assembly: its package name, what it is for, and the capability
/// ids it links in index order.
pub struct Assembly {
    pub name: String,
    /// The generated UI it links for, if any.
    pub ui: Option<String>,
    pub about: String,
    pub caps: Vec<String>,
}

fn capability_ids(root: &Path) -> Vec<String> {
    let mut ids: Vec<String> = fs::read_dir(root.join("crates"))
        .expect("crates/")
        .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
        .filter_map(|name| name.strip_prefix("cap-").map(str::to_string))
        .filter(|id| id != "abi")
        .collect();
    ids.sort();
    ids
}

fn ui_assemblies(root: &Path, known: &[String]) -> Vec<Assembly> {
    let uis = root.join("web/src/uis");
    let mut dirs: Vec<PathBuf> = fs::read_dir(&uis)
        .expect("web/src/uis/")
        .filter_map(|entry| Some(entry.ok()?.path()))
        .filter(|path| path.join("ui.json").is_file())
        .collect();
    dirs.sort();
    dirs.into_iter()
        .map(|dir| {
            let path = dir.join("ui.json");
            let ui: serde_json::Value =
                serde_json::from_slice(&fs::read(&path).expect("ui.json reads")).expect("ui.json parses");
            let id = ui["id"].as_str().expect("ui.json names its id").to_string();
            let caps: BTreeSet<String> = ui["ops"]
                .as_array()
                .unwrap_or_else(|| panic!("{} lists no ops", path.display()))
                .iter()
                .map(|op| {
                    let op = op.as_str().expect("an op is a string");
                    let (cap, _) = op.split_once('.').unwrap_or_else(|| panic!("op {op:?} is not <cap>.<op>"));
                    assert!(known.iter().any(|k| k == cap), "{}: no capability {cap:?}", path.display());
                    cap.to_string()
                })
                .collect();
            Assembly {
                name: format!("module-ui-{id}"),
                ui: Some(id.clone()),
                about: format!("the {id} UI's capabilities (web/src/uis/{id}/ui.json), linked into one module"),
                caps: caps.into_iter().collect(),
            }
        })
        .collect()
}

/// The assemblies the tree asks for: every capability alone, then
/// every generated UI's.
pub fn assemblies(root: &Path) -> Vec<Assembly> {
    let ids = capability_ids(root);
    let mut out: Vec<Assembly> = ids
        .iter()
        .map(|id| Assembly { name: format!("module-{id}"), ui: None, about: format!("the {id} capability alone"), caps: vec![id.clone()] })
        .collect();
    out.extend(ui_assemblies(root, &ids));
    out
}

pub fn files(assembly: &Assembly) -> Vec<(String, String)> {
    let header = "# GENERATED by gen-assemblies (`just caps`) — do not edit; regenerate.\n";
    let deps: String =
        assembly.caps.iter().map(|id| format!("cap-{id} = {{ path = \"../../crates/cap-{id}\" }}\n")).collect();
    let cargo = format!(
        "{header}[package]\nname = \"{name}\"\ndescription = \"An assembly: {about}.\"\nversion.workspace = true\nedition.workspace = true\nlicense.workspace = true\npublish = false\n\n[lib]\ncrate-type = [\"cdylib\"]\n\n[dependencies]\ncap-abi = {{ path = \"../../crates/cap-abi\" }}\n{deps}",
        name = assembly.name,
        about = assembly.about,
    );
    let caps: Vec<String> = assembly.caps.iter().map(|id| format!("cap_{}::CAPABILITY", id.replace('-', "_"))).collect();
    let lib = format!(
        "//! GENERATED by gen-assemblies (`just caps`) — do not edit; regenerate.\n//!\n//! An assembly: {about}. The four exports, over one kernel registry\n//! per document kind; a capability's bulk ops carry its index (in\n//! this order) in the high 16 bits.\n\ncap_abi::assembly!({caps});\n",
        about = assembly.about,
        caps = caps.join(", "),
    );
    vec![("Cargo.toml".to_string(), cargo), ("src/lib.rs".to_string(), lib)]
}

