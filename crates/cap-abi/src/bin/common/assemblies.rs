#![allow(dead_code)] // each bin uses part of the listing
//! The assemblies the tree asks for, and the files that are each one
//! (shared by gen-assemblies, which writes them, and the generator,
//! which records them). gen-assemblies also writes the generator's
//! binary, gen-manifest ([`generator_files`]), from the same list of
//! capability directories.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

/// One assembly: its package name, what it is for, and the capability
/// ids it links in index order.
pub struct Assembly {
    pub name: String,
    /// The generated UI it links for, if any.
    pub ui: Option<String>,
    pub about: String,
    pub caps: Vec<String>,
}

fn capability_ids(root: &Path) -> Vec<String> {
    let mut ids: Vec<String> = fs::read_dir(root.join("crates"))
        .expect("crates/")
        .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
        .filter_map(|name| name.strip_prefix("cap-").map(str::to_string))
        .filter(|id| id != "abi")
        .collect();
    ids.sort();
    ids
}

fn ui_assemblies(root: &Path, known: &[String]) -> Vec<Assembly> {
    let uis = root.join("web/src/uis");
    let mut dirs: Vec<PathBuf> = fs::read_dir(&uis)
        .expect("web/src/uis/")
        .filter_map(|entry| Some(entry.ok()?.path()))
        .filter(|path| path.join("ui.json").is_file())
        .collect();
    dirs.sort();
    dirs.into_iter()
        .map(|dir| {
            let path = dir.join("ui.json");
            let ui: serde_json::Value =
                serde_json::from_slice(&fs::read(&path).expect("ui.json reads")).expect("ui.json parses");
            let id = ui["id"].as_str().expect("ui.json names its id").to_string();
            let caps: BTreeSet<String> = ui["ops"]
                .as_array()
                .unwrap_or_else(|| panic!("{} lists no ops", path.display()))
                .iter()
                .map(|op| {
                    let op = op.as_str().expect("an op is a string");
                    let (cap, _) = op.split_once('.').unwrap_or_else(|| panic!("op {op:?} is not <cap>.<op>"));
                    assert!(known.iter().any(|k| k == cap), "{}: no capability {cap:?}", path.display());
                    cap.to_string()
                })
                .collect();
            Assembly {
                name: format!("module-ui-{id}"),
                ui: Some(id.clone()),
                about: format!("the {id} UI's capabilities (web/src/uis/{id}/ui.json), linked into one module"),
                caps: caps.into_iter().collect(),
            }
        })
        .collect()
}

/// The assemblies the tree asks for: every capability alone, then
/// every generated UI's.
pub fn assemblies(root: &Path) -> Vec<Assembly> {
    let ids = capability_ids(root);
    let mut out: Vec<Assembly> = ids
        .iter()
        .map(|id| Assembly { name: format!("module-{id}"), ui: None, about: format!("the {id} capability alone"), caps: vec![id.clone()] })
        .collect();
    out.extend(ui_assemblies(root, &ids));
    out
}

pub fn files(assembly: &Assembly) -> Vec<(String, String)> {
    let header = "# GENERATED by gen-assemblies (`just caps`) — do not edit; regenerate.\n";
    let deps: String =
        assembly.caps.iter().map(|id| format!("cap-{id} = {{ path = \"../../crates/cap-{id}\" }}\n")).collect();
    let cargo = format!(
        "{header}[package]\nname = \"{name}\"\ndescription = \"An assembly: {about}.\"\nversion.workspace = true\nedition.workspace = true\nlicense.workspace = true\npublish = false\n\n[lib]\ncrate-type = [\"cdylib\"]\n\n[dependencies]\ncap-abi = {{ path = \"../../crates/cap-abi\" }}\n{deps}",
        name = assembly.name,
        about = assembly.about,
    );
    let caps: Vec<String> = assembly.caps.iter().map(|id| format!("cap_{}::CAPABILITY", id.replace('-', "_"))).collect();
    let lib = format!(
        "//! GENERATED by gen-assemblies (`just caps`) — do not edit; regenerate.\n//!\n//! An assembly: {about}. The four exports, over one kernel registry\n//! per document kind; a capability's bulk ops carry its index (in\n//! this order) in the high 16 bits.\n\ncap_abi::assembly!({caps});\n",
        about = assembly.about,
        caps = caps.join(", "),
    );
    vec![("Cargo.toml".to_string(), cargo), ("src/lib.rs".to_string(), lib)]
}


/// The generated generator binary's directory and package name. It is a
/// crate in `assemblies/` beside the modules, and no module build
/// selects it.
pub const GENERATOR: &str = "gen-manifest";

/// The files of gen-manifest: a crate that links every capability with
/// its `examples` feature and hands them to the generator library as
/// data (`generator::Linked`), in id order. Its tests run the two checks
/// that run every capability (`generator::checks`). So no hand-written
/// code names a capability, and a fresh clone builds: nothing hand-written
/// depends on this crate.
pub fn generator_files(root: &Path) -> Vec<(String, String)> {
    let ids = capability_ids(root);
    let header = "# GENERATED by gen-assemblies (`just caps`) — do not edit; regenerate.\n";
    let deps: String = ids
        .iter()
        .map(|id| format!("cap-{id} = {{ path = \"../../crates/cap-{id}\", features = [\"examples\"] }}\n"))
        .collect();
    let cargo = format!(
        "{header}[package]\nname = \"{GENERATOR}\"\ndescription = \"The generator's binary: every capability, with its worked examples, handed to the generator library.\"\nversion.workspace = true\nedition.workspace = true\nlicense.workspace = true\npublish = false\n\n[dependencies]\ngenerator = {{ path = \"../../crates/generator\" }}\n{deps}"
    );
    let linked: String = ids
        .iter()
        .map(|id| {
            let krate = format!("cap_{}", id.replace('-', "_"));
            format!("        generator::Linked {{ declared: {krate}::declaration(), examples: {krate}::examples::examples }},\n")
        })
        .collect();
    let generated = "//! GENERATED by gen-assemblies (`just caps`) — do not edit; regenerate.\n";
    let lib = format!(
        "{generated}//!\n//! Every capability, in id order, as the generator reads it.\n\npub fn capabilities() -> Vec<generator::Linked> {{\n    vec![\n{linked}    ]\n}}\n"
    );
    let main = format!("{generated}//!\n//! gen-manifest: the generator over every capability (`just caps`).\n\nfn main() {{\n    generator::main(&gen_manifest::capabilities());\n}}\n");
    let tests = format!(
        "{generated}//!\n//! The checks that run every capability's dispatch over the locked\n//! schemas (`generator::checks`).\n\n#[test]\nfn every_document_a_capability_answers_matches_its_locked_schema() {{\n    generator::checks::real_output(&gen_manifest::capabilities());\n}}\n\n#[test]\nfn the_agencys_feed_answers_documents_that_match_their_schemas() {{\n    generator::checks::soak(&gen_manifest::capabilities());\n}}\n"
    );
    vec![
        ("Cargo.toml".to_string(), cargo),
        ("src/lib.rs".to_string(), lib),
        ("src/main.rs".to_string(), main),
        ("tests/schemas.rs".to_string(), tests),
    ]
}
