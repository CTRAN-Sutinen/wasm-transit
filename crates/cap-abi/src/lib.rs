//! cap-abi — the kernel, and the capability-module ABI shell.
//!
//! The capability-module ABI: four exports, zero imports, every host
//! trivial. A capability differs in *which ops* its dispatch answers,
//! never in how it is called — so the shell is a macro here instead of
//! a copy per crate.
//!
//! Protocol (the same contract every module speaks):
//!
//! * `transit_alloc(len) -> ptr`, `transit_free(ptr, len)`;
//! * `transit_invoke(ptr, len) -> ptr` — JSON request in,
//!   `[u32 LE len][{"ok": ...} | {"error": ...}]` out;
//! * `transit_invoke_bytes(op, ptr, len) -> ptr` — the bulk-payload
//!   form for bytes (a feed zip, an rt payload, a gzipped network — a
//!   JSON array of numbers would be absurd).
//!
//! A module is an ASSEMBLY of one or more capabilities over the
//! kernel ([`kernel`]): the kernel owns the registries (one per
//! document kind) and the loads that fill them, and routes each call.
//! A capability's own bulk ops number 0–255 (an assembly of several
//! carries the capability's index in the high 16 bits); kernel ops
//! number from 256 and mean the same thing in every module: the loads
//! for the kinds its capabilities read (each kind's code is its
//! library's, `transit_version::Load::CODE`), and the registry ops
//! [`registry::OP_EVICT`] (257) and [`registry::OP_HELD`] (258).
//!
//! A capability crate REGISTERS — it never exports:
//!
//! ```ignore
//! // In the capability crate's lib.rs:
//! cap_abi::capability! {
//!     id: "board",
//!     json: dispatch_json,
//!     bytes: dispatch_bytes,
//!     documents: [Network, EditDocument, LiveDay, Watchlist],
//!     request: Request,
//! }
//! ```
//!
//! and an assembly crate (generated by `gen-assemblies`) emits the four
//! exports once, over the capabilities it links:
//!
//! ```ignore
//! cap_abi::assembly!(cap_board::CAPABILITY, cap_rt::CAPABILITY);
//! ```
//!
//! The unsafe exports live here; a capability crate forbids `unsafe`.

/// Declare a capability: `CAPABILITY` (what an assembly links), and
/// its native seam — `invoke`, `invoke_bytes`, `registries` — the
/// capability alone, exactly as its one-capability module answers
/// (the kernel's loads included), for the crate's tests and native
/// hosts.
///
/// `json` is `fn(&str) -> String`; `bytes` is `fn(u32, &[u8]) ->
/// String` (the op code is the capability's own, 0–255, advertised in
/// the manifest). `documents` names the types of the kinds it reads
/// (each one's library implements `transit_version::Load`; `[]` for a
/// stateless capability): their loads are kernel ops in every module
/// that links it, and the registry ops answer over them.
///
/// The rest is what the manifest records ([`kernel::Declared`]):
/// `request` is the capability's `Request` enum, whose op tags are its
/// ops; `consumes`, `speaks`, and `migrates` (each `&[]` when left out)
/// are the kinds it reads as another capability's answer, the versions
/// it reads, and the version steps it carries. Its `OPS.md` is read from
/// the crate's root.
#[macro_export]
macro_rules! capability {
    (
        id: $id:literal,
        json: $json:path,
        bytes: $bytes:path,
        documents: [$($kind:ty),* $(,)?],
        request: $request:ty
        $(, consumes: $consumes:expr)?
        $(, speaks: $speaks:expr)?
        $(, migrates: $migrates:expr)?
        $(,)?
    ) => {
        /// This capability, as an assembly links it.
        pub static CAPABILITY: $crate::kernel::Cap = $crate::kernel::Cap {
            id: $id,
            json: $json,
            bytes: $bytes,
            documents: &[$($crate::kernel::loader::<$kind>),*],
        };

        /// This capability's declaration, as the generator reads it.
        pub fn declaration() -> $crate::kernel::Declared {
            $crate::kernel::Declared {
                id: $id,
                invoke,
                invoke_bytes,
                ops: $crate::kernel::op_names::<$request>(),
                documents: CAPABILITY.documents.iter().map(|k| k().id()).collect(),
                consumes: $crate::__or!([$($consumes)?] &[]),
                speaks: $crate::__or!([$($speaks)?] &[]),
                migrates: $crate::__or!([$($migrates)?] &[]),
                docs: include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/OPS.md")),
            }
        }

        /// The JSON lane of this capability's one-capability module.
        pub fn invoke(text: &str) -> String {
            $crate::kernel::invoke(&[&CAPABILITY], text)
        }

        /// The bulk lane of this capability's one-capability module.
        pub fn invoke_bytes(op: u32, bytes: &[u8]) -> String {
            $crate::kernel::invoke_bytes(&[&CAPABILITY], op, bytes)
        }

        /// The registries its module holds (what evict and held answer over).
        pub fn registries() -> Vec<&'static dyn $crate::registry::Held> {
            $crate::kernel::registries(&[&CAPABILITY])
        }
    };
}

/// The given expression, or the default when none is given
/// (`capability!`'s optional fields).
#[doc(hidden)]
#[macro_export]
macro_rules! __or {
    ([] $default:expr) => {
        $default
    };
    ([$given:expr] $default:expr) => {
        $given
    };
}

/// Emit the four-export flat ABI over the capabilities an assembly
/// links (in index order: a capability's bulk ops carry its index in
/// the high 16 bits). Used once per module, by a generated assembly
/// crate.
#[macro_export]
macro_rules! assembly {
    ($($cap:path),+ $(,)?) => {
        /// The capabilities this module links, in index order.
        pub static CAPS: &[&$crate::kernel::Cap] = &[$(&$cap),+];

        /// Result buffers carry a u32 length prefix.
        const LEN_PREFIX: usize = 4;

        /// Many allocators return null for zero-size requests;
        /// normalize so alloc/free stay symmetric on both sides.
        fn layout(len: usize) -> std::alloc::Layout {
            std::alloc::Layout::from_size_align(len.max(1), 1)
                .expect("allocation is always valid")
        }

        #[no_mangle]
        pub extern "C" fn transit_alloc(len: usize) -> *mut u8 {
            let ptr = unsafe { std::alloc::alloc(layout(len)) };
            if ptr.is_null() {
                std::alloc::handle_alloc_error(layout(len));
            }
            ptr
        }

        /// # Safety
        /// `ptr` must come from [`transit_alloc`] or a result buffer,
        /// with the length it was allocated with.
        #[no_mangle]
        pub unsafe extern "C" fn transit_free(ptr: *mut u8, len: usize) {
            if !ptr.is_null() {
                std::alloc::dealloc(ptr, layout(len));
            }
        }

        /// Serialize an outcome into a fresh `[len][payload]` buffer.
        fn write_result(json: String) -> *mut u8 {
            let payload = json.as_bytes();
            let total = LEN_PREFIX + payload.len();
            let ptr = transit_alloc(total);
            unsafe {
                let buf = std::slice::from_raw_parts_mut(ptr, total);
                buf[..LEN_PREFIX].copy_from_slice(&(payload.len() as u32).to_le_bytes());
                buf[LEN_PREFIX..].copy_from_slice(payload);
            }
            ptr
        }

        /// # Safety
        /// `ptr` must point to `len` readable UTF-8 bytes.
        #[no_mangle]
        pub unsafe extern "C" fn transit_invoke(ptr: *const u8, len: usize) -> *mut u8 {
            write_result(match std::str::from_utf8(std::slice::from_raw_parts(ptr, len)) {
                Ok(text) => $crate::kernel::invoke(CAPS, text),
                Err(_) => r#"{"error":"invalid request: payload is not UTF-8"}"#.to_string(),
            })
        }

        /// # Safety
        /// `ptr` must point to `len` readable bytes.
        #[no_mangle]
        pub unsafe extern "C" fn transit_invoke_bytes(op: u32, ptr: *const u8, len: usize) -> *mut u8 {
            write_result($crate::kernel::invoke_bytes(CAPS, op, std::slice::from_raw_parts(ptr, len)))
        }
    };
}


// A document's identity and its versioned read live in transit-version,
// so each kind's library reads and hashes its own kind (D-239). The
// kernel and every capability reach them here, as before.
pub use transit_version::document::{
    canonical_bytes, canonical_hash, content_hash, is_gzip, noting_read, parse_document, parse_versioned, read_versioned,
    versioned, ReadAhead,
};
use transit_version::document::read_value;
pub use transit_version::jcs;

/// A record's identity in a log (D-190): the canonical hash of the
/// record as stored. A record that does not serialize gets a name that
/// never equals a hash. cap-log and every receive op name records by it.
pub fn record_hash(value: &serde_json::Value) -> String {
    canonical_hash(value).unwrap_or_else(|e| format!("unhashable: {e}"))
}

/// A document carried inside an op's answer as its canonical bytes,
/// exactly: a host that serves it under its hash serves those bytes
/// (the import's network and boundary, the streets, the walk table, a
/// pick read over the stops). It reads back as the document. It writes
/// those bytes only into an answer serde_json writes ([`outcome`]); to
/// hash it, hash the document inside (`.0`).
#[derive(Debug, Clone, PartialEq)]
pub struct Canonical<T>(pub T);

impl<T: serde::Serialize> serde::Serialize for Canonical<T> {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        use serde::ser::Error;
        let text = jcs::to_string(&self.0).map_err(S::Error::custom)?;
        let raw = serde_json::value::RawValue::from_string(text).map_err(S::Error::custom)?;
        raw.serialize(s)
    }
}

impl<'de, T: serde::Deserialize<'de>> serde::Deserialize<'de> for Canonical<T> {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        T::deserialize(d).map(Canonical)
    }
}

impl<T> std::ops::Deref for Canonical<T> {
    type Target = T;
    fn deref(&self) -> &T {
        &self.0
    }
}

/// A request field holding a document in the version this build
/// reads, or the next one it reads ahead ([`versioned`]): another
/// version fails the request, naming both (docs/FORMATS.md, "Versions").
/// It is for a document an op reads. The base of an op that answers the
/// next document is a [`Base`]. Reads as the document (`Deref`); on the
/// wire it is the document itself (`#[ts(as = "T")]` on the field).
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(transparent)]
pub struct Current<T>(pub T);

impl<'de, T> serde::Deserialize<'de> for Current<T>
where
    T: serde::de::DeserializeOwned + transit_version::Versioned,
{
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        versioned(<serde_json::Value as serde::Deserialize>::deserialize(d)?).map(Current).map_err(serde::de::Error::custom)
    }
}

impl<T> std::ops::Deref for Current<T> {
    type Target = T;
    fn deref(&self) -> &T {
        &self.0
    }
}

/// A request field holding the document an op writes over: it answers
/// the next document from this one. It reads like [`Current`], and also
/// refuses a copy read ahead through a read-only step, naming both
/// versions (D-186). On the wire it is the document itself.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(transparent)]
pub struct Base<T>(pub T);

impl<'de, T> serde::Deserialize<'de> for Base<T>
where
    T: serde::de::DeserializeOwned + transit_version::Versioned,
{
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let (document, read) = read_value::<T>(<serde_json::Value as serde::Deserialize>::deserialize(d)?).map_err(serde::de::Error::custom)?;
        if let Some(read) = read {
            transit_version::writes_over::<T>(read.found, transit_version::ReadAs::Ahead(read.how)).map_err(serde::de::Error::custom)?;
        }
        Ok(Base(document))
    }
}

/// A whole document that a write sends, read as the base of the write
/// ([`Base`]), and the fields it carries that this build does not know
/// (D-167). A receive op reads a whole-document write with it.
pub fn read_base<T: serde::de::DeserializeOwned + transit_version::Versioned>(doc: serde_json::Value) -> Result<(T, Vec<String>), String> {
    let (read, unknown) = transit_version::noting_unknown(|| serde_json::from_value::<Base<T>>(doc));
    Ok((read.map_err(|e| e.to_string())?.0, unknown))
}

impl<T> std::ops::Deref for Base<T> {
    type Target = T;
    fn deref(&self) -> &T {
        &self.0
    }
}

/// The version check every versioned kind's load makes: the document's
/// version is the one this build reads, or the load is refused naming
/// both — an older one with the capability op that migrates it, a
/// newer one as written by a newer build (refused, never rewritten).
pub fn speaks(kind: &str, found: u32, reads: u32) -> Result<(), String> {
    if found == reads {
        Ok(())
    } else {
        Err(transit_version::refused(kind, found, reads))
    }
}

/// The JSON lane every module answers: `{"op": ...}` in, the
/// request decoded into the module's typed `Request` and answered by
/// its `dispatch`, as [`outcome`] — `{"ok": ...}` / `{"error": ...}`,
/// a total seam (an undecodable request is an error, never a panic).
pub fn answer<Q: serde::de::DeserializeOwned, A: serde::Serialize>(
    text: &str,
    dispatch: impl FnOnce(Q) -> Result<A, String>,
) -> String {
    let (request, unknown) = transit_version::noting_unknown(|| serde_json::from_str::<Q>(text));
    REQUEST_UNKNOWN.with(|noted| *noted.borrow_mut() = unknown);
    let answered = match request {
        Ok(request) => outcome(dispatch(request)),
        Err(error) => outcome::<()>(Err(format!("invalid request: {error}"))),
    };
    REQUEST_UNKNOWN.with(|noted| noted.borrow_mut().clear());
    answered
}

thread_local! {
    static REQUEST_UNKNOWN: std::cell::RefCell<Vec<String>> = const { std::cell::RefCell::new(Vec::new()) };
}

/// The names of the fields the documents in the request being answered
/// carry that this build does not know (D-167), in name order. A
/// receive op (a `validate`) answers them, so the receive path flags
/// them for a person. Empty outside [`answer`].
pub fn request_unknown_fields() -> Vec<String> {
    REQUEST_UNKNOWN.with(|noted| noted.borrow().clone())
}

/// The `{"ok": ..} | {"error": ..}` outcome every op answers,
/// serialized directly: no intermediate `serde_json::Value` — which
/// would hold a second copy of the answer, and in which a document
/// carried as its canonical bytes ([`Canonical`]) would not cross as
/// those bytes (docs/FORMATS.md).
pub fn outcome<T: serde::Serialize>(result: Result<T, String>) -> String {
    #[derive(serde::Serialize)]
    enum Outcome<T> {
        #[serde(rename = "ok")]
        Ok(T),
        #[serde(rename = "error")]
        Error(String),
    }
    let outcome = match result {
        Ok(value) => Outcome::Ok(value),
        Err(error) => Outcome::Error(error),
    };
    serde_json::to_string(&outcome).expect("dispatch outcomes serialize")
}

