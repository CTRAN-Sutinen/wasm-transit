//! cap-abi — the kernel, and the capability-module ABI shell.
//!
//! The capability-module ABI: four exports, zero imports, every host
//! trivial. A capability differs in *which ops* its dispatch answers,
//! never in how it is called — so the shell is a macro here instead of
//! a copy per crate.
//!
//! Protocol (the same contract every module speaks):
//!
//! * `transit_alloc(len) -> ptr`, `transit_free(ptr, len)`;
//! * `transit_invoke(ptr, len) -> ptr` — JSON request in,
//!   `[u32 LE len][{"ok": ...} | {"error": ...}]` out;
//! * `transit_invoke_bytes(op, ptr, len) -> ptr` — the bulk-payload
//!   form for bytes (a feed zip, an rt payload, a gzipped network — a
//!   JSON array of numbers would be absurd).
//!
//! A module is an ASSEMBLY of one or more capabilities over the
//! kernel ([`kernel`]): the kernel owns the registries (one per
//! document kind) and the loads that fill them, and routes each call.
//! A capability's own bulk ops number 0–255 (an assembly of several
//! carries the capability's index in the high 16 bits); kernel ops
//! number from 256 and mean the same thing in every module: the loads
//! ([`OP_LOAD_NETWORK`] and [`kernel`]'s `OP_LOAD_*`) for the kinds its
//! capabilities read, and the registry ops [`registry::OP_EVICT`]
//! (257) and [`registry::OP_HELD`] (258).
//!
//! A capability crate REGISTERS — it never exports:
//!
//! ```ignore
//! // In the capability crate's lib.rs:
//! cap_abi::capability! {
//!     id: "board",
//!     json: dispatch_json,
//!     bytes: dispatch_bytes,
//!     documents: [NETWORK, EDITS, LIVE, WATCHLIST],
//! }
//! ```
//!
//! and an assembly crate (generated by `gen-assemblies`) emits the four
//! exports once, over the capabilities it links:
//!
//! ```ignore
//! cap_abi::assembly!(cap_board::CAPABILITY, cap_rt::CAPABILITY);
//! ```
//!
//! The unsafe exports live here; a capability crate forbids `unsafe`.

/// Declare a capability: `CAPABILITY` (what an assembly links), and
/// its native seam — `invoke`, `invoke_bytes`, `registries` — the
/// capability alone, exactly as its one-capability module answers
/// (the kernel's loads included), for the crate's tests and native
/// hosts.
///
/// `json` is `fn(&str) -> String`; `bytes` is `fn(u32, &[u8]) ->
/// String` (the op code is the capability's own, 0–255, advertised in
/// the manifest). `documents` names the kernel kinds it reads
/// ([`kernel::NETWORK`], [`kernel::EDITS`], …; `[]` for a stateless
/// capability): their loads are kernel ops in every module that links
/// it, and the registry ops answer over them.
#[macro_export]
macro_rules! capability {
    (id: $id:literal, json: $json:path, bytes: $bytes:path, documents: [$($kind:ident),* $(,)?] $(,)?) => {
        /// This capability, as an assembly links it.
        pub static CAPABILITY: $crate::kernel::Cap = $crate::kernel::Cap {
            id: $id,
            json: $json,
            bytes: $bytes,
            documents: &[$(&$crate::kernel::$kind),*],
        };

        /// The JSON lane of this capability's one-capability module.
        pub fn invoke(text: &str) -> String {
            $crate::kernel::invoke(&[&CAPABILITY], text)
        }

        /// The bulk lane of this capability's one-capability module.
        pub fn invoke_bytes(op: u32, bytes: &[u8]) -> String {
            $crate::kernel::invoke_bytes(&[&CAPABILITY], op, bytes)
        }

        /// The registries its module holds (what evict and held answer over).
        pub fn registries() -> Vec<&'static dyn $crate::registry::Held> {
            $crate::kernel::registries(&[&CAPABILITY])
        }
    };
}

/// Emit the four-export flat ABI over the capabilities an assembly
/// links (in index order: a capability's bulk ops carry its index in
/// the high 16 bits). Used once per module, by a generated assembly
/// crate.
#[macro_export]
macro_rules! assembly {
    ($($cap:path),+ $(,)?) => {
        /// The capabilities this module links, in index order.
        pub static CAPS: &[&$crate::kernel::Cap] = &[$(&$cap),+];

        /// Result buffers carry a u32 length prefix.
        const LEN_PREFIX: usize = 4;

        /// Many allocators return null for zero-size requests;
        /// normalize so alloc/free stay symmetric on both sides.
        fn layout(len: usize) -> std::alloc::Layout {
            std::alloc::Layout::from_size_align(len.max(1), 1)
                .expect("allocation is always valid")
        }

        #[no_mangle]
        pub extern "C" fn transit_alloc(len: usize) -> *mut u8 {
            let ptr = unsafe { std::alloc::alloc(layout(len)) };
            if ptr.is_null() {
                std::alloc::handle_alloc_error(layout(len));
            }
            ptr
        }

        /// # Safety
        /// `ptr` must come from [`transit_alloc`] or a result buffer,
        /// with the length it was allocated with.
        #[no_mangle]
        pub unsafe extern "C" fn transit_free(ptr: *mut u8, len: usize) {
            if !ptr.is_null() {
                std::alloc::dealloc(ptr, layout(len));
            }
        }

        /// Serialize an outcome into a fresh `[len][payload]` buffer.
        fn write_result(json: String) -> *mut u8 {
            let payload = json.as_bytes();
            let total = LEN_PREFIX + payload.len();
            let ptr = transit_alloc(total);
            unsafe {
                let buf = std::slice::from_raw_parts_mut(ptr, total);
                buf[..LEN_PREFIX].copy_from_slice(&(payload.len() as u32).to_le_bytes());
                buf[LEN_PREFIX..].copy_from_slice(payload);
            }
            ptr
        }

        /// # Safety
        /// `ptr` must point to `len` readable UTF-8 bytes.
        #[no_mangle]
        pub unsafe extern "C" fn transit_invoke(ptr: *const u8, len: usize) -> *mut u8 {
            write_result(match std::str::from_utf8(std::slice::from_raw_parts(ptr, len)) {
                Ok(text) => $crate::kernel::invoke(CAPS, text),
                Err(_) => r#"{"error":"invalid request: payload is not UTF-8"}"#.to_string(),
            })
        }

        /// # Safety
        /// `ptr` must point to `len` readable bytes.
        #[no_mangle]
        pub unsafe extern "C" fn transit_invoke_bytes(op: u32, ptr: *const u8, len: usize) -> *mut u8 {
            write_result($crate::kernel::invoke_bytes(CAPS, op, std::slice::from_raw_parts(ptr, len)))
        }
    };
}

/// Kernel bulk op: register the network document from its JSON bytes,
/// or those bytes gzipped (a published network crosses compressed —
/// [`parse_document`]), in every module whose capabilities read
/// networks — the same answer and the same hash as the JSON op
/// `load_network`.
///
/// The bytes are the bare document (no request envelope), parsed
/// straight into the typed model; the JSON lane's envelope is peeled
/// with the document left raw ([`kernel`]), so registration never
/// buffers the input into a generic tree (~8× the document on a real
/// network, and wasm memory never shrinks back from a peak).
pub const OP_LOAD_NETWORK: u32 = 256;

/// "sha256:<hex>" of bytes — the content-hash formula every module
/// and host shares.
pub fn content_hash(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    format!("sha256:{:x}", Sha256::digest(bytes))
}

/// A document's identity: the content hash of its canonical
/// serialization (serde_json, struct field order). Streamed into the
/// digest, so hashing never holds a second copy of the document —
/// byte-identical to hashing `serde_json::to_string(value)`.
pub fn canonical_hash<T: serde::Serialize>(value: &T) -> Result<String, String> {
    use sha2::{Digest, Sha256};

    struct Digesting(Sha256);
    impl std::io::Write for Digesting {
        fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
            self.0.update(buf);
            Ok(buf.len())
        }
        fn flush(&mut self) -> std::io::Result<()> {
            Ok(())
        }
    }

    let mut digest = Digesting(Sha256::new());
    serde_json::to_writer(&mut digest, value).map_err(|e| format!("document does not serialize: {e}"))?;
    Ok(format!("sha256:{:x}", digest.0.finalize()))
}

/// Whether bulk bytes are a gzip stream (its magic bytes — no JSON
/// document starts with 0x1f).
pub fn is_gzip(bytes: &[u8]) -> bool {
    bytes.starts_with(&[0x1f, 0x8b])
}

/// Parse a kernel document from bulk bytes, straight into its type:
/// the document's JSON, or that JSON gzipped. A gzipped document is
/// decoded AS IT PARSES — its text never exists whole in the module,
/// so registration's peak is the parsed document plus the compressed
/// input, not the text beside it (wasm memory never shrinks back from
/// a peak). The identity is the parsed document's canonical hash
/// either way, so both forms register the same document.
pub fn parse_document<T: serde::de::DeserializeOwned>(bytes: &[u8]) -> Result<T, String> {
    let source: Box<dyn std::io::Read + '_> = if is_gzip(bytes) { Box::new(flate2::read::GzDecoder::new(bytes)) } else { Box::new(bytes) };
    serde_json::from_reader(std::io::BufReader::with_capacity(64 * 1024, source)).map_err(|e| format!("invalid document: {e}"))
}

/// Parse a document of a versioned kind from bulk bytes (JSON or
/// gzipped JSON), in the version this build reads and only that: an
/// older document is refused with the op that brings it forward, a
/// newer one naming both versions — never parsed and re-emitted
/// (docs/FORMATS.md, "Versions"). A copy with no version field is the
/// kind's untagged version.
pub fn parse_versioned<T>(bytes: &[u8]) -> Result<T, String>
where
    T: serde::de::DeserializeOwned + transit_version::Versioned,
{
    match parse_document::<T>(bytes) {
        Ok(document) => speaks(T::KIND, document.schema_version(), T::READS).map(|_| document),
        // The typed read failed: an older or newer shape says so by its
        // version; a document in this version is just malformed.
        Err(typed) => match parse_document::<serde_json::Value>(bytes) {
            Ok(value) => speaks(T::KIND, version_in::<T>(&value), T::READS).and(Err(typed)),
            Err(_) => Err(typed),
        },
    }
}

/// [`parse_versioned`] over a value already parsed (a request field).
pub fn versioned<T>(value: serde_json::Value) -> Result<T, String>
where
    T: serde::de::DeserializeOwned + transit_version::Versioned,
{
    speaks(T::KIND, version_in::<T>(&value), T::READS)?;
    serde_json::from_value(value).map_err(|e| format!("invalid document: {e}"))
}

/// A request field holding a document in the version this build
/// reads ([`versioned`]): another version fails the request, naming
/// both. Reads as the document (`Deref`); on the wire it is the
/// document itself (`#[ts(as = "T")]` on the field).
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(transparent)]
pub struct Current<T>(pub T);

impl<'de, T> serde::Deserialize<'de> for Current<T>
where
    T: serde::de::DeserializeOwned + transit_version::Versioned,
{
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        versioned(<serde_json::Value as serde::Deserialize>::deserialize(d)?).map(Current).map_err(serde::de::Error::custom)
    }
}

impl<T> std::ops::Deref for Current<T> {
    type Target = T;
    fn deref(&self) -> &T {
        &self.0
    }
}

/// The version a copy of `T`'s kind carries in its version field.
fn version_in<T: transit_version::Versioned>(value: &serde_json::Value) -> u32 {
    value.get(T::VERSION_FIELD).and_then(serde_json::Value::as_u64).map_or(T::UNTAGGED, |v| v as u32)
}

/// Parse a network document from bulk bytes ([`parse_versioned`]).
pub fn parse_network(bytes: &[u8]) -> Result<transit_network::Network, String> {
    parse_versioned(bytes)
}

/// The version check every versioned kind's load makes: the document's
/// version is the one this build reads, or the load is refused naming
/// both — an older one with the capability op that migrates it, a
/// newer one as written by a newer build (refused, never rewritten).
pub fn speaks(kind: &str, found: u32, reads: u32) -> Result<(), String> {
    use std::cmp::Ordering::*;
    match found.cmp(&reads) {
        Equal => Ok(()),
        Less => Err(format!(
            "{kind} v{found}: this module reads v{reads} — bring it forward first (migrate.migrate, kind {kind:?})"
        )),
        Greater => Err(format!(
            "{kind} v{found} is newer than this module, which reads v{reads}: a newer build wrote it (refused, never rewritten)"
        )),
    }
}

/// The JSON lane every module answers: `{"op": ...}` in, the
/// request decoded into the module's typed `Request` and answered by
/// its `dispatch`, as [`outcome`] — `{"ok": ...}` / `{"error": ...}`,
/// a total seam (an undecodable request is an error, never a panic).
pub fn answer<Q: serde::de::DeserializeOwned, A: serde::Serialize>(
    text: &str,
    dispatch: impl FnOnce(Q) -> Result<A, String>,
) -> String {
    match serde_json::from_str::<Q>(text) {
        Ok(request) => outcome(dispatch(request)),
        Err(error) => outcome::<()>(Err(format!("invalid request: {error}"))),
    }
}

/// The `{"ok": ..} | {"error": ..}` outcome every op answers,
/// serialized directly: no intermediate `serde_json::Value` — which
/// would hold a second copy of the answer and sort its keys, so a
/// document inside it (an import's network) would not cross as its
/// canonical bytes (struct field order, docs/FORMATS.md).
pub fn outcome<T: serde::Serialize>(result: Result<T, String>) -> String {
    #[derive(serde::Serialize)]
    enum Outcome<T> {
        #[serde(rename = "ok")]
        Ok(T),
        #[serde(rename = "error")]
        Error(String),
    }
    let outcome = match result {
        Ok(value) => Outcome::Ok(value),
        Err(error) => Outcome::Error(error),
    };
    serde_json::to_string(&outcome).expect("dispatch outcomes serialize")
}

